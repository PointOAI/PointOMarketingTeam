import assert from "node:assert/strict";
import { start, req, sleep, waitStatus } from "./lib-fake.mjs";
const app = await start();
await req(app, "POST", "/api/team/recommended", {});
const id = (await req(app, "POST", "/api/tasks", { title: "Race", description: "[slow]", type: "social_post", platforms: ["x"], assignee: { mode: "manager" } })).json.task.id;
await waitStatus(app, id, "briefing"); await sleep(50);
await req(app, "POST", `/api/tasks/${id}/cancel`, {});
const r = await req(app, "POST", `/api/tasks/${id}/retry`, {});
assert.equal(r.status, 200);
await sleep(500);
const st = (await req(app, "GET", "/api/state")).json;
const mgr = st.team.find((m) => m.roleId === "manager");
assert.equal(st.tasks[0].status, "briefing");
assert.equal(mgr.status, "working", "new run's member status survives stale run cleanup");
assert.equal(mgr.currentTaskId, id);
assert.equal((await req(app, "DELETE", `/api/team/${mgr.id}`)).status, 409);
await req(app, "POST", `/api/tasks/${id}/cancel`, {});
await app.close();
console.log("ok cancel->retry race");
